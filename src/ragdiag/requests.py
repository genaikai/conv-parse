"""판정자가 적은 요구가 이전 질문들에 실제로 있는지 **코드가 확인한다.**

전에는 판정자에게 근거 구절을 베껴 적게 하고 그것을 원문과 대조했다
(`verify_request_quote`). 강한 모델에서는 돌았지만 약한 모델에서 뒤집혔다.

  Qwen3.5-9B 실측 (골든셋 145건, 2026-09)
    requested_format 을 맞게 읽은 뒤 requested_quote 를 비운 경우   27건 중 27건
    → 대조가 전부 떨어지고, **맞는 요구가 없던 것으로 지워졌다**

대조 규칙은 "인용을 못 대면 요구가 없었다" 를 전제한다. 그 전제가 깨지면 규칙이
지어낸 요구가 아니라 맞는 요구를 지운다. 약한 모델은 베끼는 일 자체를 안 한다.

그래서 증거를 **요구하지 않고 확인한다.** 판정자가 `table` 이라고 하면 이전
질문들에 표를 뜻하는 말이 있는지 코드가 본다. 원래 막으려던 병(후속 발화에서
처음 나온 요구를 어겼다고 적는 것)은 그대로 막힌다 - 그런 요구는 이전 질문에
어휘가 없다.

**후보를 찾는 것과 답을 확인하는 것은 다른 문제다.** 아무 단서 없이 형식을 찾아내는
탐지기를 만들어 재봤더니 IFEval-Ko 342건에서 정밀도 64% 였다("큰따옴표로" 를 표
요구로 읽었다). 확인은 판정자가 이미 답을 말한 뒤라 그 하나만 보면 되고, 훨씬 좁다.

언어와 길이는 값까지 확인하지 않는다. 세상의 언어를 열거할 수 없고(외부 데이터에
칸나다어 · 펀자비어 · 스와힐리어가 나온다), 길이의 단위도 열려 있다(줄 · 자 · 단어 ·
문장 · 단락 · 페이지). 대신 **그런 요구가 있었는지만** 본다 - 어느 언어인지 · 몇
줄인지는 판정자를 믿는다. 층을 그렇게 가른다.

패턴은 `tests/test_requests.py` 가 외부 데이터셋(IFEval-Ko)으로 고정한다. 우리
골든셋으로만 재면 그 셋의 표현에 맞춘 정규식이 100% 를 내고 끝난다.
"""

from __future__ import annotations

import re

# 한국어 수사. 문자 클래스로 쓰면 "여행" 이 "여"+"행"(단위)으로 읽힌다 - 실제로
# IFEval-Ko 에서 6건이 그렇게 걸렸다. 온전한 낱말만 받는다.
_NUM = r"(?:\d+|한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|스물|서른)"

# --- 형식 ------------------------------------------------------------------
#
# 닫힌 집합이라 값마다 어휘를 둘 수 있다.
#
# "표" 는 다른 낱말의 꼬리이기도 하다 - 따옴표 · 물음표 · 느낌표 · 쉼표 · 구두점 ·
# 목표 · 대표 · 지표 · 발표 · 투표 · 좌표. 앞 글자를 막는 목록(blocklist)으로 풀면
# 빠뜨린 글자마다 오탐이 난다. 그래서 반대로 간다: **낱말 경계에서 시작하는 것만**
# 받는다. 한글에는 \b 가 없으므로 앞이 글자가 아닌 것을 직접 본다.
_STARTS_WORD = r"(?<![0-9A-Za-z가-힣])"

FORMAT_VOCAB = {
    # 표로 · 표를 · 표 형태 · 테이블로 · 도표.
    #
    # 두 갈래로 받는다. 낱말 경계에서 시작하는 "표"(띄어 쓴 글), 그리고 앞에 조사가
    # 붙어 버린 "…을표로"(띄어쓰기 없는 실제 로그). 뒤 갈래는 경계를 못 쓰므로
    # "표" 로 끝나는 낱말만 막는다 - 따옴표 · 물음표 · 느낌표 · 쉼표 · 구두점 ·
    # 목표 · 대표 · 지표 · 발표 · 투표 · 좌표 · 상표.
    #
    # "테이블" 은 홀로는 안 받는다. "임원 급여 테이블을 보여주세요" 는 형식 요구가
    # 아니라 자료 요청이고, "피벗 테이블 만드는 법" 은 도구 사용법이다 - 우리
    # 골든셋에서 실제로 셋이 그렇게 걸렸다. 형식을 지시하는 꼴에서만 받는다.
    "table": _STARTS_WORD + r"(?:표|도표)(?:\s|로|를|에|와|의|$)|"
             + r"(?<![따옴물음느낌쉼구두목대지발투좌상별])(?<!시간)표\s*(?:로|를|형(?:태|식))|"
             + r"(?:테이블|table)\s*(?:로|형(?:태|식))|행과\s*열|열과\s*행",
    "numbered_list": _STARTS_WORD + r"(?:번호|넘버링|순번)|숫자를?\s*매|"
                     r"1\.\s*2\.|①|순서대로\s*나열",
    # "***로 구분" 도 "*로 시작" 도 불릿이 아니다 - 앞은 단락 구분자, 뒤는 강조
    # 표시다. 둘을 넣었다가 오탐 15건이 났다. 목록 · 리스트는 형식을 지시하는
    # 자리에서만 받는다. "글머리" 는 홀로 쓰이는 일이 많아 기호를 요구하지 않는다.
    "bullet_list": _STARTS_WORD + r"(?:불릿|bullet|글머리)|"
                   r"(?:목록|리스트|list)\s*(?:으로|로|형(?:태|식))",
    "code_block": r"코드\s*블[록럭]|code\s*block|```|백틱|backtick",
    "json": r"json|제이슨",
    "prose": r"줄글|산문|서술형|문단\s*으로\s*(?:풀|써|작성|설명)|"
             r"문장\s*으로\s*(?:풀|써|작성|설명)|표\s*(?:는)?\s*말고|목록\s*말고",
}

# --- 언어 ------------------------------------------------------------------
#
# 값(어느 언어인가)은 확인하지 않는다. 열거가 불가능하다. "언어 요구가 있었는가" 만 본다.
#
# "단어" · "용어" · "국어" 처럼 어(語)로 끝나는 보통명사가 많아서, 뒤에 붙는 조사와
# 쓰임을 함께 본다. 쓰임의 동사는 넓게 잡는다 - "~어로 해야", "~어로 되어 있는지",
# "~어로 다시 작성" 이 전부 같은 요구인데 동사만 다르다.
# 어(語) 앞이 한 글자면 언어 이름인지 보통명사인지 글자 수로는 못 가른다 -
# "영어" 와 "단어" 가 같은 꼴이다. {2,10} 으로 막으면 "영어로 답해 주세요" 가
# 통째로 떨어지고, {1,10} 으로 열면 "단어로 설명해 주세요" 가 들어온다.
# 그래서 한 글자짜리는 **알려진 언어명만** 따로 받는다. 두 글자 이상은 열어 둔다 -
# 일본어 · 중국어 · 스와힐리어 · 구자라티어가 전부 그쪽이고, 열거할 수 없다.
_SHORT_LANG = r"(?:영|독|불|노|일|중|러|헌)어"
# 문(文) 꼴도 같은 요구다 - "영문으로 작성하세요" 는 "영어로" 와 같은 말이다.
# 다만 문으로 끝나는 보통명사가 아주 많아서(논문 · 본문 · 주문 · 질문 · 설문 · 전문)
# **알려진 언어 앞글자만** 받는다. 어 꼴처럼 열어 두면 걸리는 게 너무 많다.
_LANG_MUN = r"(?:영|국|한|독|불|노|일|중|러)문"
_LANG_NOUN = r"(?:" + _SHORT_LANG + r"|" + _LANG_MUN + r"|[가-힣A-Za-z]{2,10}(?:어|말|語))"
_LANG_USE = (r"(?:답|응답|작성|번역|써|쓰|설명|말|표현|해야|하여|해서|되어|되도록|"
             r"되었|바꾸|다시|사용)")
# 이름만으로 언어임이 분명한 것과, 보통명사일 수도 있는 것을 갈라 다루게 한다.
# 분명한 쪽은 조사만 보면 된다 - "영문으로 400자 이상의 블로그 게시물을 작성하세요"
# 처럼 동사가 멀리 떨어진 꼴이 흔해서, 동사를 요구하면 절반을 놓친다(실측 37%).
# 애매한 쪽([가-힣]{2,10}어 - 외래어 · 표준어 · 유행어도 여기 들어온다)은 그대로
# 쓰임을 함께 본다.
_CLEAR_LANG = r"(?:" + _SHORT_LANG + r"|" + _LANG_MUN + r")"

LANGUAGE_MARKER = (
    _LANG_NOUN + r"\s*(?:로만|으로만)|"
    + _LANG_NOUN + r"\s*만\s*(?:사용|써|쓰|작성|허용)|"
    + _CLEAR_LANG + r"\s*(?:로|으로)|"
    + _LANG_NOUN + r"\s*(?:로|으로)\s*\S{0,6}\s*" + _LANG_USE + r"|"
    + r"(?:전적으로|오직|반드시)\s*" + _LANG_NOUN + r"|"
    + _LANG_NOUN + r"\s*(?:사용하여|사용해서|를\s*사용)|"
    r"\b(?:in|into)\s+[A-Z][a-z]{2,}\b|\brespond\s+in\b|\banswer\s+in\b|"
    r"[一-鿿ぁ-ゟ゠-ヿ]{1,6}語で"
)

# --- 길이 ------------------------------------------------------------------
#
# 단위가 열려 있다. 우리 taxonomy 는 자 · 문장 · 줄 셋뿐이지만 사람은 단어 · 단락 ·
# 페이지로도 요구한다. 값은 판정자를 믿고 "분량 요구가 있었는가" 만 본다.
#
# 섹션 · 개 · 가지는 뺀다 - 분량이 아니라 구조를 세는 말이라("정확히 3개 섹션"),
# 넣었더니 음성 261건 중 89건이 통과했다. 수사만 있고 단위가 없는 꼴
# ("최소 3", "정확히 두")도 뺀다. 무엇을 세는지 모르면 분량 요구가 아니다.
_COUNT_UNIT = (r"(?:자|글자|단어|낱말|문장|줄|행|단락|문단|페이지|쪽|"
               r"words?|sentences?|paragraphs?|lines?|characters?)")

# "3개의 단락" 처럼 세는 말이 끼는 꼴이 흔하다. 수사와 단위 사이를 비워 둔다.
_COUNTER = r"(?:\s*(?:개|가지)?(?:의)?\s*)"

# 단위 뒤의 경계. 자 · 줄 · 행 · 쪽은 한 글자라 다른 낱말의 머리이기도 하다 -
# "12개의 **자**리 표시자", "위한 **자**기소개서", "**줄**거리" 가 전부 걸렸다.
# 조사가 한글이라 "뒤가 한글이면 거절" 로는 "단어를" 까지 떨어진다. 그래서 붙을 수
# 있는 조사를 열거하고, 그 밖에 한글이 이어지면 다른 낱말로 본다.
_ENDS_WORD = (r"(?:(?![가-힣])|(?=(?:로|으로|를|을|은|는|이|가|의|와|과|에|도|만|"
              r"씩|이상|이하|이내|미만|초과|정도|가량|짜리|내외|넘|당)))")

LENGTH_MARKER = (
    _STARTS_WORD + _NUM + _COUNTER + _COUNT_UNIT + _ENDS_WORD + r"|"
    # "수" 는 뺀다 - "도와**줄 수** 있나요" 가 걸린다 (IFEval-Ko 오탐 10건).
    + _COUNT_UNIT + r"\s*(?:이내|이하|이상|미만|초과)|"
    r"(?:짧|간략|축약)(?:게|히|하게|해|해서)|"
    r"간단(?:히|하게)\s*\S{0,4}\s*(?:답|써|쓰|작성|설명|요약)|"
    r"(?:요약|축약)\s*(?:해|만|본|하여)|"
    # "자세히 · 상세히" 는 뺀다. 분량이 아니라 상세함을 요구하는 말이라, 넣으면
    # "자세히 설명해 주세요" 가 전부 길이 요구가 된다 (IFEval-Ko 오탐 2건).
    r"길게\s*\S{0,4}\s*(?:써|쓰|작성|설명|답)|"
    r"한\s*(?:줄|문장|단락)(?![가-힣])"
)

_FORMAT = {k: re.compile(v, re.I) for k, v in FORMAT_VOCAB.items()}
_LANGUAGE = re.compile(LANGUAGE_MARKER, re.I)
_LENGTH = re.compile(LENGTH_MARKER, re.I)


def format_is_supported(kind: str, questions: list[str]) -> bool:
    """판정자가 말한 형식을 뜻하는 말이 이전 질문들에 있는가."""
    pattern = _FORMAT.get(kind)
    return bool(pattern) and any(pattern.search(q or "") for q in questions)


def language_was_requested(questions: list[str]) -> bool:
    """언어를 지정하는 말이 이전 질문들에 있는가. 어느 언어인지는 보지 않는다."""
    return any(_LANGUAGE.search(q or "") for q in questions)


def length_was_requested(questions: list[str]) -> bool:
    """분량을 지정하는 말이 이전 질문들에 있는가. 몇인지는 보지 않는다."""
    return any(_LENGTH.search(q or "") for q in questions)

"""kev 문항 — 범주 판정 전부가 여기 있다.

prompts.py 가 일반 LLM 의 프롬프트라면 여기는 분류 모델(kev)의 문항이다. kev 는
yes/no(noul) · 택일(choice) · 점수(score) 세 유형만 받고 보정된 확률을 낸다. 문장은
못 만든다 — 문장이 필요한 칸은 prompts.py 의 ②b · ④a · 인용으로 간다.

문항 id 는 Observation 의 필드 이름과 같다. 답을 Observation 에 그대로 부을 수 있다.

**지시문은 판정 기준만 적는다.** 관측 프롬프트에 있던 긴 예시와 경계 설명을 그대로 옮긴
것이다 — 모델이 바뀌어도 기준은 같아야 한다.
"""

from __future__ import annotations

from typing import Any


def noul(instructions: str, true: str = "", false: str = "") -> dict:
    q: dict[str, Any] = {"type": "noul", "instructions": instructions}
    if true or false:
        q["criteria"] = {"true": true, "false": false}
    return q


def choice(instructions: str, options: dict[str, str | None]) -> dict:
    return {"type": "choice", "instructions": instructions, "criteria": dict(options)}


